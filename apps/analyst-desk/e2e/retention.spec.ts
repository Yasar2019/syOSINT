import {expect,test} from '@playwright/test';

test('previews cleanup and places/releases a hold without deleting synthetic intake',async({page})=>{
 const api='http://127.0.0.1:8765';
 const feed=await page.request.post(`${api}/feeds`,{data:{name:'Retention synthetic fixture',url:'https://retention.example',feed_url:'https://retention.example/rss.xml',language:'en'}});
 expect(feed.status()).toBe(201);
 const source=await feed.json() as {id:number};
 expect((await page.request.post(`${api}/feeds/${source.id}/collect`)).ok()).toBe(true);
 const items=await (await page.request.get(`${api}/intake-items`)).json() as {id:number;source_id:number}[];
 const item=items.find(value=>value.source_id===source.id)!;
 expect(item).toBeTruthy();
 const before=await (await page.request.get(`${api}/audit`)).json();
 await page.goto('/maintenance');
 await expect(page.getByText('Preview mode — deletion disabled')).toBeVisible();
 await expect(page.getByRole('button',{name:'Delete eligible private data'})).toHaveCount(0);
 await page.getByRole('button',{name:'Refresh cleanup preview'}).click();
 await expect(page.getByRole('heading',{name:'Cleanup preview'})).toBeVisible();
 expect(await (await page.request.get(`${api}/audit`)).json()).toEqual(before);
 await page.getByLabel('Record type').selectOption('intake');
 await page.getByLabel('Record ID',{exact:true}).fill(String(item.id));
 await page.getByLabel('Preservation reason',{exact:true}).fill('Preserve synthetic retention fixture');
 await page.getByRole('button',{name:'Place preservation hold'}).click();
 const hold=page.getByRole('article').filter({hasText:'Preserve synthetic retention fixture'});
 await expect(hold).toBeVisible();
 await hold.getByLabel('Release reason').fill('Synthetic review completed');
 await hold.getByRole('button',{name:'Release hold'}).click();
 await expect(hold.getByText(/Released/)).toBeVisible();
 const after=await (await page.request.get(`${api}/intake-items`)).json() as {id:number}[];
 expect(after.some(value=>value.id===item.id)).toBe(true);
});
