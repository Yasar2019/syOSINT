import { expect, test } from '@playwright/test';

test('correct and withdraw a synthetic exported incident with explicit local approvals', async ({ page }) => {
  const api = 'http://127.0.0.1:8765';
  const fields = { title_en: 'Synthetic revision original', title_ar: 'تقرير تجريبي أصلي', category: 'infrastructure', summary_en: 'Synthetic original claim', summary_ar: 'ادعاء تجريبي', uncertainty_en: 'Unconfirmed', uncertainty_ar: 'غير مؤكد', location_en: 'Syria', location_ar: 'سوريا', precision: 'country', occurred_at: '2026-10-14T10:00:00Z', confidence: 'unverified' };
  const review = { rationale: 'Synthetic public source assessed locally', independence_checked: true, time_checked: true, location_checked: true, contradictions_checked: true, person_safety_checked: true, operational_safety_checked: true, contradictions_acknowledged: true, human_approved: true };
  const source = await page.request.post(`${api}/sources`, { data: { name: 'Revision fixture journal', url: 'https://revision.example', language: 'en' } });
  expect(source.status()).toBe(201);
  const sourceId = (await source.json()).id;
  const created = await page.request.post(`${api}/incidents`, { data: { title_en: fields.title_en, title_ar: fields.title_ar, category: fields.category } });
  expect(created.status()).toBe(201);
  const id = (await created.json()).id;
  const url = `${api}/incidents/${id}`;
  expect((await page.request.put(url, { data: fields })).status()).toBe(200);
  expect((await page.request.post(`${url}/evidence`, { data: { source_id: sourceId, url: 'https://revision.example/report', text: 'PRIVATE SYNTHETIC EVIDENCE', published_at: fields.occurred_at } })).status()).toBe(201);
  for (const state of ['investigating', 'review-ready']) expect((await page.request.post(`${url}/transition`, { data: { state, reason: 'Synthetic review progression' } })).status()).toBe(200);
  expect((await page.request.post(`${url}/review`, { data: review })).status()).toBe(200);
  expect((await page.request.post(`${url}/transition`, { data: { state: 'approved', reason: 'Synthetic approved case' } })).status()).toBe(200);
  expect((await page.request.post(`${url}/export`, { data: { acknowledged: true } })).status()).toBe(200);
  const read = async () => (await (await page.request.get(`${url}/publication`)).json());
  const submit = async (name: string) => {
    const response = page.waitForResponse(r => r.request().method() === 'POST' && r.url().startsWith('http://127.0.0.1:3001/'));
    await page.getByRole('button', { name, exact: true }).click();
    await response;
    await page.waitForLoadState('networkidle');
  };
  await page.goto(`/incident/${id}`);
  await page.getByRole('link', { name: /publication/i }).click();
  await expect(page).toHaveURL(new RegExp(`/incident/${id}/publication`));
  await page.locator('input[name="title_en"]').fill('Synthetic revised title');
  await page.getByLabel('Correction reason · English').fill('Corrected after synthetic review');
  await page.getByLabel('سبب التصحيح · عربي').fill('تصحيح بعد مراجعة تجريبية');
  await submit('Save correction draft');
  expect((await read()).version).toBe(1);
  expect((await read()).record.title.en).toBe(fields.title_en);
  await expect(page.getByRole('button', { name: 'Approve correction locally', exact: true })).toHaveCount(0);
  await page.getByLabel('Written rationale').fill(review.rationale);
  for (const key of Object.keys(review).filter(key => key !== 'rationale')) await page.locator(`input[name="${key}"]`).check();
  await submit('Record correction review');
  await expect(page.getByRole('heading', { name: 'Exact correction preview' })).toBeVisible();
  await page.getByLabel('I reviewed this exact correction preview and approve the local revision').check();
  await submit('Approve correction locally');
  expect((await read()).version).toBe(2);
  expect((await read()).record.id).toBe(`incident-${id}`);
  expect((await read()).record.status).toBe('corrected');
  await page.getByLabel('I checked this exact public record and authorize a local export').check();
  await submit('Export sanitized JSON locally');
  await page.goto(`/incident/${id}/publication`);
  await page.getByLabel('Withdrawal reason · English').fill('Withdrawn after synthetic reassessment');
  await page.getByLabel('سبب السحب · عربي').fill('سحب بعد إعادة تقييم تجريبية');
  await submit('Preview withdrawal');
  expect((await read()).version).toBe(2);
  await page.getByLabel('I reviewed this exact withdrawal preview and approve the local revision').check();
  await submit('Approve withdrawal locally');
  await expect.poll(async () => (await read()).version).toBe(3);
  const withdrawn = await read();
  expect(withdrawn.history.map((x: {action:string}) => x.action)).toEqual(['published', 'corrected', 'withdrawn']);
  expect(withdrawn.record.id).toBe(`incident-${id}`);
  expect(withdrawn.record.status).toBe('withdrawn');
  expect(withdrawn.record.sources).toEqual([]);
  expect(JSON.stringify(withdrawn.record)).not.toContain('Synthetic original claim');
  expect(JSON.stringify(withdrawn.record)).not.toContain('revision.example');
  expect(JSON.stringify(withdrawn.record)).not.toContain('PRIVATE SYNTHETIC EVIDENCE');
  await expect(page.getByRole('button', { name: 'Save correction draft', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Preview withdrawal', exact: true })).toHaveCount(0);
  await page.getByLabel('I checked this exact public record and authorize a local export').check();
  await submit('Export sanitized JSON locally');
  const finalExport = await page.request.post(`${url}/export`, { data: { acknowledged: true } });
  expect((await finalExport.json()).record).toEqual(withdrawn.record);
});
